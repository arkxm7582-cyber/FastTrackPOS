    private void loadDeliveryShipmentsToTable() {
        DefaultTableModel model = new DefaultTableModel(new Object[]{"ID", "Content", "Package Status", "Address"}, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false; // Make table read-only
            }
        };

        for (Shipment shipment : shipments) {
            PackageStatus status = shipment.getPackageStatus();

            if (status == PackageStatus.ORDER_PLACED ||
                status == PackageStatus.PICKED_UP_BY_COURIER ||
                status == PackageStatus.AT_DESTINATION_WAREHOUSE ||
                status == PackageStatus.OUT_FOR_DELIVERY) {

                String statusDisplay;
                switch (status) {
                    case ORDER_PLACED:
                        statusDisplay = "Order Pick Up";
                        break;
                    case AT_DESTINATION_WAREHOUSE:
                        statusDisplay = "Delivery";
                        break;
                    default:
                        statusDisplay = status.name().replace('_', ' ').toLowerCase();
                        statusDisplay = Character.toUpperCase(statusDisplay.charAt(0)) + statusDisplay.substring(1); // Capitalize first letter
                        break;
                }

                model.addRow(new Object[]{
                    shipment.getId(),
                    shipment.getPackageContent(),
                    statusDisplay,
                    shipment.getAddress()
                });
            }
        }

        deliveries.setModel(model);

        // Set table row height
        deliveries.setRowHeight(25);

        // Center column headers
        ((DefaultTableCellRenderer) deliveries.getTableHeader().getDefaultRenderer())
                .setHorizontalAlignment(JLabel.CENTER);

        // Set column alignment
        DefaultTableCellRenderer centerRenderer = new DefaultTableCellRenderer();
        centerRenderer.setHorizontalAlignment(JLabel.CENTER);
        for (int i = 0; i < deliveries.getColumnCount(); i++) {
            deliveries.getColumnModel().getColumn(i).setCellRenderer(centerRenderer);
        }

        // Make table not editable
        deliveries.setDefaultEditor(Object.class, null);

        // Improve header appearance
        deliveries.getTableHeader().setFont(new Font("Segoe UI", Font.BOLD, 14));
        deliveries.getTableHeader().setBackground(new Color(100, 149, 237));
        deliveries.getTableHeader().setForeground(Color.WHITE);

        // Set grid and selection color
        deliveries.setGridColor(Color.LIGHT_GRAY);
        deliveries.setSelectionBackground(new Color(173, 216, 230));
    }


