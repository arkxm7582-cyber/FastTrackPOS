    private void deliveriesMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_deliveriesMouseClicked
        // TODO add your handling code here:
        if (evt.getClickCount() == 2) { // Double click
            int selectedRow = deliveries.getSelectedRow();
            if (selectedRow >= 0) {
                // Get Shipment ID from the table
                int shipmentId = (int) deliveries.getValueAt(selectedRow, 0);
                String deliveryType = deliveries.getValueAt(selectedRow, 2).toString();

                // Find the Shipment from the list
                selectedShipment = null;
                for (Shipment s : shipments) {
                    if (s.getId() == shipmentId) {
                        selectedShipment = s;
                        break;
                    }
                }

                if (selectedShipment != null) {
                    showViewOrderDialog(selectedShipment);
                }
                address.setText(selectedShipment.getAddress());
                String[] items = selectedShipment.getPackageContent().split(" /\\*/ ");
                StringBuilder formattedContent = new StringBuilder();
                formattedContent.append("<html>");
                for (String item : items) {
                    if (!item.trim().isEmpty()) {
                        formattedContent.append("• ").append(item.trim()).append(" <br>");
                    }
                }
                formattedContent.append("</html>");
                
                System.out.println("current User" + currentUser);
                System.out.println("selected" + selectedShipment);

               if (deliveryType.equals("Order Pick Up"))
               {
                   jLabel4.setText(deliveryType);
                   jButton1.setText("Mark as picked up");
                   selectedShipment.setPackageStatus(PackageStatus.PICKED_UP_BY_COURIER);
               }
               else if (deliveryType.equals("Delivery")) {
                   jLabel4.setText(deliveryType);
                   jButton1.setText("Mark as delivered");
                   selectedShipment.setPackageStatus(PackageStatus.DELIVERED_TO_RECIPIENT);
               } else {
                   jButton1.setVisible(false);
               }
                pkgeContent.setText(formattedContent.toString());
                
                
            }
        }

    }//GEN-LAST:event_deliveriesMouseClicked

