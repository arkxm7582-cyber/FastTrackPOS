    private void loginBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_loginBtnActionPerformed
        String email = emailTxt.getText().trim();
        String password = new String(passTxt.getPassword()).trim();

        // === Validation checks ===
        if (email.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Email cannot be empty.", "Validation Error", JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (!email.matches("^[A-Za-z0-9+_.-]+@[A-Za-z0-9.-]+$")) {
            JOptionPane.showMessageDialog(this, "Please enter a valid email address.", "Validation Error", JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (password.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Password cannot be empty.", "Validation Error", JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (password.length() < 6) {
            JOptionPane.showMessageDialog(this, "Password must be at least 6 characters long.", "Validation Error", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        CustomerController controller = new CustomerController();

        AuthenticationController login = new AuthenticationController();
        LoginResult result = login.authenticate(emailTxt.getText(), password);
        
          if (result.success) {
            JOptionPane.showMessageDialog(this, result.message);
            User loggedInUser = result.user;
            System.out.println("user from login session " + loggedInUser);
            switch (loggedInUser.getRole())
            {
                case CUSTOMER:
                    Customer cstomer = controller.getCustomerByUserId(loggedInUser.getId());
                    CustomerSession.setCurrentCustomer(cstomer);
                    System.out.println("CUSTOMER FROM LOGIN " + getCurrentCustomer());

                    CustomerDashboard dash = new CustomerDashboard();
                    dash.setVisible(true);
                    
                    this.dispose();
                    break;
                
                case AGENT:
                    AgentDashboard agent = new AgentDashboard(loggedInUser);
                    agent.setVisible(true);
                    this.dispose();
                    break;
                    
                case WAREHOUSE:
                    WarehouseList warehouse = new WarehouseList(loggedInUser);
                    warehouse.setVisible(true);
                    this.dispose();
                    break;
            }
            
            Session.setCurrentUser(loggedInUser);

        } else {
            JOptionPane.showMessageDialog(this, result.message, "Login Failed", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_loginBtnActionPerformed

