    private void continueBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_continueBtnActionPerformed
// TODO add your handling code here:

        UserRole role = (UserRole) rolesCmb.getSelectedItem();
        String email = registerEmailTxt.getText().trim();
        String password = new String(registerPassword.getPassword()).trim();
        String firstName = registerFirstNameTxt.getText().trim();
        String lastName = registerLastNameTxt.getText().trim();

        // Validate fields
        if (email.isEmpty() || password.isEmpty() || firstName.isEmpty() || role == null) {
            JOptionPane.showMessageDialog(this, "All fields must be filled out before proceeding.", "Validation Error", JOptionPane.WARNING_MESSAGE);
            return;
        }

        // Optional: Validate email format (basic)
        if (!email.matches("^\\S+@\\S+\\.\\S+$")) {
            JOptionPane.showMessageDialog(this, "Please enter a valid email address.", "Invalid Email", JOptionPane.WARNING_MESSAGE);
            return;
        }

        // Optional: Validate password length
        if (password.length() < 6) {
            JOptionPane.showMessageDialog(this, "Password must be at least 6 characters long.", "Invalid Password", JOptionPane.WARNING_MESSAGE);
            return;
        }

        // Create user and open appropriate registration dialog
        User user = new User(email, password, role, firstName + " " + lastName);
        System.out.println("USER REG: " + user.toString());

        switch (role) {
            case AGENT:
                RegisterAgent agent = new RegisterAgent(user);
                agent.setVisible(true);
                break;
            case CUSTOMER:
                RegisterCustomer cust = new RegisterCustomer(user);
                cust.setVisible(true);
                break;
            case WAREHOUSE:
                RegisterWarehouse warehouse = new RegisterWarehouse(user);
                warehouse.setVisible(true);
                break;
        }

        this.dispose();

    }//GEN-LAST:event_continueBtnActionPerformed

