    private void addVehicleBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addVehicleBtnActionPerformed
    VehicleType vehicleType = (VehicleType) vehicleTypeCmb.getSelectedItem();
    String model = modelTxt.getText().trim();
    String regNum = regNumTxt.getText().trim();

    // Validation
    if (model.isEmpty() || regNum.isEmpty()) {
        JOptionPane.showMessageDialog(addVehicleDialog, "Model and Registration Number must not be empty.", "Validation Error", JOptionPane.WARNING_MESSAGE);
        return;
    }

    if (vehicleType == null) {
        JOptionPane.showMessageDialog(addVehicleDialog, "Please select a vehicle type.", "Validation Error", JOptionPane.WARNING_MESSAGE);
        return;
    }

    // Create vehicle and update preview
    v = new Vehicle(model, regNum, vehicleType);
    prevModel.setText(v.getModel());
    prevNumber.setText(v.getNumberPlate());
    prevType.setText(v.getVehicleType().name());

    // Insert vehicle
    InsertResult result = vController.insertVehicle(v);

    if (result.success) {
        JOptionPane.showMessageDialog(addVehicleDialog, result.message, "Register Vehicle", JOptionPane.INFORMATION_MESSAGE);
        addVehicleDialog.setVisible(false); // only close on success
    } else {
        JOptionPane.showMessageDialog(addVehicleDialog, result.message, "Registration Failed", JOptionPane.ERROR_MESSAGE);
    }

    }//GEN-LAST:event_addVehicleBtnActionPerformed

