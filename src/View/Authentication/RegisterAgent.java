    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
    AgentController aController = new AgentController();

    // Validate text fields
    String nic = nicTxt.getText().trim();
    String telephone = teleTxt.getText().trim();

    if (nic.isEmpty() || telephone.isEmpty()) {
        JOptionPane.showMessageDialog(this, "NIC and Telephone fields must be filled.", "Validation Error", JOptionPane.WARNING_MESSAGE);
        return;
    }

    // Validate warehouse selection
    Object selectedWarehouse = warehouseCmb.getSelectedItem();
    if (!(selectedWarehouse instanceof Warehouse)) {
        JOptionPane.showMessageDialog(this, "Please select a valid warehouse.", "Validation Error", JOptionPane.WARNING_MESSAGE);
        return;
    }
    int wareHouseId = ((Warehouse) selectedWarehouse).getId();

    // Validate vehicle
    if (v == null || v.getNumberPlate() == null || v.getNumberPlate().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, "You must add/select a vehicle before registering the agent.", "Validation Error", JOptionPane.WARNING_MESSAGE);
        return;
    }

    int vehicleId = vController.getVehicleIdByNumberPlate(v.getNumberPlate());
    if (vehicleId == -1) {
        JOptionPane.showMessageDialog(this, "Vehicle not found in the system. Please make sure it's registered.", "Validation Error", JOptionPane.WARNING_MESSAGE);
        return;
    }

    System.out.println("Vehicle ID: " + vehicleId);
    System.out.println("Vehicle: " + v);
    System.out.println("User: " + user);

    Agent a = new Agent(wareHouseId, v.getId(), nic, telephone, user.getEmail(), user.getPassword(), UserRole.AGENT, user.getName());
    System.out.println("Agent: " + a);

    InsertResult result = aController.insertAgent(a);

    if (result.success) {
        JOptionPane.showMessageDialog(this, result.message, "Success", JOptionPane.INFORMATION_MESSAGE);
        this.dispose();
        Login login = new Login();
        login.setVisible(true);
    } else {
        JOptionPane.showMessageDialog(this, result.message, "Agent Registration Failed", JOptionPane.ERROR_MESSAGE);
    }

    }//GEN-LAST:event_jButton2ActionPerformed

