    private void registerBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_registerBtnActionPerformed
        CustomerController cuscontroller = new CustomerController();

        // Gather inputs
        String streetNumber = streetNumberTxt.getText().trim();
        String streetName = streetNameTxt.getText().trim();
        String city = cityNameTxt.getText().trim();
        String district = districtTxt.getText().trim();
        String telephone = teleTxt.getText().trim();
        String nic = nicTxt.getText().trim();
        Warehouse selectedWarehouse = (Warehouse) warehouseCmb.getSelectedItem();

        // Validate inputs
        if (streetNumber.isEmpty() || streetName.isEmpty() || city.isEmpty() || district.isEmpty() ||
            telephone.isEmpty() || nic.isEmpty() || selectedWarehouse == null) {
            JOptionPane.showMessageDialog(this, "All fields must be filled and a warehouse must be selected.", "Validation Error", JOptionPane.WARNING_MESSAGE);
            return;
        }

        // Optionally validate phone and NIC formats
        if (!telephone.matches("\\d{10}")) {
            JOptionPane.showMessageDialog(this, "Telephone must be 10 digits.", "Validation Error", JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (!nic.matches("[0-9]{9}[vVxX]|[0-9]{12}")) {
            JOptionPane.showMessageDialog(this, "NIC format is invalid.", "Validation Error", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            // Compose address and customer
            String address = streetNumber + " " + streetName + " " + city + " " + district;
            int wareHouseId = selectedWarehouse.getId();

            Customer cus = new Customer(
                address,
                telephone,
                nic,
                wareHouseId,
                user.getEmail(),
                user.getName(),
                user.getPassword(),
                UserRole.CUSTOMER
            );

            InsertResult result = cuscontroller.insertCustomer(cus);

            if (result.success) {
                JOptionPane.showMessageDialog(this, result.message, "Success", JOptionPane.INFORMATION_MESSAGE);
                Login login = new Login();
                login.setVisible(true);
                this.dispose();
            } else {
                JOptionPane.showMessageDialog(this, result.message, "Customer Registration Failed", JOptionPane.ERROR_MESSAGE);
            }

        } catch (NullPointerException npe) {
            JOptionPane.showMessageDialog(this, "Please ensure all values are correctly entered.", "Error", JOptionPane.ERROR_MESSAGE);
            System.err.println("NullPointerException: " + npe.getMessage());
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "An unexpected error occurred: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
        }

        
    }//GEN-LAST:event_registerBtnActionPerformed

