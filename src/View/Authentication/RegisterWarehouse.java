    private void registerBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_registerBtnActionPerformed
// TODO add your handling code here:
        try {
            // Validate required fields
            if (streetNumberTxt.getText().trim().isEmpty() ||
                streetNameTxt.getText().trim().isEmpty() ||
                cityNameTxt.getText().trim().isEmpty() ||
                teleTxt.getText().trim().isEmpty() ||
                districtTxt.getText().trim().isEmpty()) {

                JOptionPane.showMessageDialog(this, "All address fields must be filled!", "Validation Error", JOptionPane.WARNING_MESSAGE);
                return;
            }

            // Print debug info
            System.out.println("User: " + user.toString());
            System.out.println(streetNumberTxt.getText() + " " + streetNameTxt.getText() + " " + cityNameTxt.getText() + " " + districtTxt.getText() + " WAREHOUSE");

            // Construct address
            String address = streetNumberTxt.getText().trim() + " " +
                             streetNameTxt.getText().trim() + ", " +
                             cityNameTxt.getText().trim() + ", " +
                             districtTxt.getText().trim();

            // Create warehouse object
            Warehouse warehouse = new Warehouse(
                address,
                districtTxt.getText().trim(),
                user.getEmail(),
                user.getPassword(),
                UserRole.WAREHOUSE,
                user.getName()
            );

            // Insert into DB
            WarehouseController controller = new WarehouseController();
            controller.insertWarehouseAndUser(warehouse);

            // Go to login screen
            this.dispose();
            Login log = new Login();
            log.setVisible(true);

        } catch (NullPointerException ex) {
            JOptionPane.showMessageDialog(this, "All fields must be filled before submitting!", "Missing Data", JOptionPane.ERROR_MESSAGE);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error occurred: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            e.printStackTrace(); // For debugging
        }

    }//GEN-LAST:event_registerBtnActionPerformed

