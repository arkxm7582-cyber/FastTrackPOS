    public CustomerRecievePackage(int id) {
        initComponents();
        this.id = id;
        jLabel6.setText(id+"");
        
        shipment = controller.getShipmentById(id);
        SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");
        deliveryDate.setText(sdf.format(shipment.getDeliveryTime()));
        
        if (shipment != null) {
            updateStatusTimeline(shipment.getPackageStatus());
        }
        
        String[] items = shipment.getPackageContent().split(" /\\*/ ");
        StringBuilder formattedContent = new StringBuilder();
        formattedContent.append("<html>");
        for (String item : items) {
            if (!item.trim().isEmpty()) {
                formattedContent.append("• ").append(item.trim()).append(" <br>");
            }
        }
        formattedContent.append("</html>");
        
        pkgeContent.setText(formattedContent.toString());
        
    }
    
    private void updateStatusTimeline(PackageStatus status) {
        PackageStatus[] statusOrder = {
            PackageStatus.ORDER_PLACED,
            PackageStatus.PICKED_UP_BY_COURIER,
            PackageStatus.AT_ORIGIN_WAREHOUSE,
            PackageStatus.IN_TRANSIT_TO_DESTINATION,
            PackageStatus.AT_DESTINATION_WAREHOUSE,
            PackageStatus.OUT_FOR_DELIVERY,
            PackageStatus.DELIVERED_TO_RECIPIENT
        };

        JLabel[] labels = {
            orderPlacedLbl,
            orderPickedupLbl,
            originWarehouse,
            inTransit,
            deliveryWarehouse,
            outforDelivery,
            delivered
        };

        boolean active = true;
        for (int i = 0; i < statusOrder.length; i++) {
            if (active) {
                if (status == statusOrder[i]) {
                    active = false; // After this, gray out
                }
            } else {
                // Grayscale all labels after current status
                ImageUtils.convertLabelImageToGrayscale(labels[i]);
            }
        }
    }


