    private void loadShipmentsIntoTable(List<Shipment> shipments) {
        String[] columnNames = { "ID", "Package Content", "Address", "Status", "Pickup Date", "Delivery Date" };
        DefaultTableModel tableModel = new DefaultTableModel(columnNames, 0) {
            // Make cells non-editable
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
        
    for (Shipment shipment : shipments) {
        // Format package content with bullets using HTML
        StringBuilder formattedContent = new StringBuilder("<html>");
        String[] items = shipment.getPackageContent().split(" /\\*/ ");
        for (String item : items) {
            if (!item.trim().isEmpty()) {
                formattedContent.append("• ").append(item.trim()).append("<br>");
            }
        }
        formattedContent.append("</html>");

        Object[] rowData = {
            shipment.getId(),
            formattedContent.toString(),
            shipment.getAddress(),
            shipment.getPackageStatus().name(),
            shipment.getPickupTime(),
            shipment.getDeliveryTime()
        };

        tableModel.addRow(rowData);
    }


        jTable1.setModel(tableModel);

        jTable1.setRowHeight(28);
        jTable1.setGridColor(new java.awt.Color(230, 230, 230));
        jTable1.setSelectionBackground(new java.awt.Color(51, 153, 255));
        jTable1.setSelectionForeground(new java.awt.Color(255, 255, 255));
        jTable1.setShowVerticalLines(false);
        jTable1.setShowHorizontalLines(true);

        // Set header font & color
        JTableHeader header = jTable1.getTableHeader();
        header.setFont(new Font("Segoe UI", Font.BOLD, 14));
        header.setBackground(new java.awt.Color(60, 63, 65));
        header.setForeground(Color.WHITE);
    }


