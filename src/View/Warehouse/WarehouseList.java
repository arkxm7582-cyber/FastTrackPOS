    public String formatShipmentDetails(ShipmentDetailsDTO dto) {
        StringBuilder sb = new StringBuilder();

        sb.append("Shipment Details\n");
        sb.append("-----------------------------\n");
        sb.append(String.format("Shipment ID        : %d\n", dto.shipmentId));
        sb.append(String.format("Package Content    : %s\n", dto.packageContent));
        sb.append(String.format("Status             : %s\n", dto.status));
        sb.append(String.format("Price              : %.2f\n", dto.price));
        sb.append(String.format("Address            : %s\n", dto.address));

        sb.append(String.format("Pickup Time        : %s\n", 
            dto.pickupTime != null ? dto.pickupTime.toString() : "N/A"));
        sb.append(String.format("Delivery Time      : %s\n", 
            dto.deliveryTime != null ? dto.deliveryTime.toString() : "N/A"));

        sb.append(String.format("Customer Email     : %s\n", dto.customerEmail));

        sb.append(String.format("Pickup Agent Name  : %s\n", 
            dto.pickupAgentName != null ? dto.pickupAgentName : "N/A"));
        sb.append(String.format("Delivery Agent Name: %s\n", 
            dto.deliveryAgentName != null ? dto.deliveryAgentName : "N/A"));

        sb.append(String.format("Pickup Warehouse   : %s\n", 
            dto.pickupWarehouseName != null ? dto.pickupWarehouseName : "N/A"));
        sb.append(String.format("Delivery Warehouse : %s\n", 
            dto.deliveryWarehouseName != null ? dto.deliveryWarehouseName : "N/A"));

        return sb.toString();
    }
    
    private void loadShipmentToDialog(int selectedRow) {
        int shipmentId = (int) jTable1.getValueAt(selectedRow, 0);
        selectedShipment = null;

        for (Shipment shipment : shipments) {
            if (shipment.getId() == shipmentId) {
                selectedShipment = shipment;
                break;
            }
        }
        
        System.out.println("status " + selectedShipment.getPackageStatus());

        if (selectedShipment != null) {
            StringBuilder content = new StringBuilder();
            String[] items = selectedShipment.getPackageContent().split(" /\\*/ ");
            for (String item : items) {
                content.append(item).append("\n");
            }

            ViewShipment.setTitle("Shipment Details - ID: " + shipmentId);
            ViewShipment.pack();
            ViewShipment.setLocationRelativeTo(null);
            ViewShipment.setVisible(true);

            addresLb.setText(selectedShipment.getAddress());
            idLbl.setText(String.valueOf(selectedShipment.getId()));
            deliveryDate.setDate(selectedShipment.getDeliveryTime());
            pickupDate.setDate(selectedShipment.getPickupTime());

            PackageStatus status = selectedShipment.getPackageStatus();
            String statusText = "";
            int warehouseId = -1;
            boolean isPickupWarehouse = false;

            // Determine if this warehouse is the pickup or delivery warehouse
            Warehouse current = warehousecontroller.getWarehouseByUserId(user.getId());
            int currentWarehouseId = current.getId(); // Warehouse currently handling this

            System.out.println("warehose" + currentWarehouseId + " " + selectedShipment.getPickupWarehouseId() + " " + selectedShipment.getDeliveryWarehouseId()); 
           if (currentWarehouseId == selectedShipment.getPickupWarehouseId()) {
                // It's the pickup warehouse
                isPickupWarehouse = true;
                warehouseId = selectedShipment.getPickupWarehouseId();

                switch (status) {
                    case ORDER_PLACED:
                    case PICKED_UP_BY_COURIER:
                    case AT_ORIGIN_WAREHOUSE:
                        System.out.println("status" + status);
                        statusText = getNextStatusText(status);
                        break;
                    default:
                        statusText = "";
                }
            } else if (currentWarehouseId == selectedShipment.getDeliveryWarehouseId()) {
                // It's the delivery warehouse
                isPickupWarehouse = false;
                warehouseId = selectedShipment.getDeliveryWarehouseId();

                switch (status) {
                    case IN_TRANSIT_TO_DESTINATION:
                    case AT_DESTINATION_WAREHOUSE:
                        statusText = getNextStatusText(status);
                        break;
                    default:
                        statusText = ""; // Don't show status at this warehouse
                }
            }
           
            if (statusText.isEmpty()) {
                StatusUpdatte.setEnabled(false);
            } else {
                StatusUpdatte.setText(statusText);
                StatusUpdatte.setVisible(true);
            }
        }
    }

    private String getStatusText(PackageStatus status) {
        switch (status) {
            case ORDER_PLACED: return "Order Placed";
            case PICKED_UP_BY_COURIER: return "Received by Courier";
            case AT_ORIGIN_WAREHOUSE: return "Sent to Transit";
            case IN_TRANSIT_TO_DESTINATION: return "Received from Transit";
            case AT_DESTINATION_WAREHOUSE: return "Out for Delivery";
            case OUT_FOR_DELIVERY: return "Delivering...";
            case DELIVERED_TO_RECIPIENT: return "Delivered";
            default: return "";
        }
    }
    
    private String getNextStatusText(PackageStatus currentStatus) {
        switch (currentStatus) {
            case ORDER_PLACED:
                return "Next: Received by Courier";
            case PICKED_UP_BY_COURIER:
                return "Next: Sent to Transit";
            case AT_ORIGIN_WAREHOUSE:
                return "Next: Received from Transit";
            case IN_TRANSIT_TO_DESTINATION:
                return "Next: Out for Delivery";
            case AT_DESTINATION_WAREHOUSE:
                return "Next: Delivering...";
            case OUT_FOR_DELIVERY:
                return "Next: Delivered";
            case DELIVERED_TO_RECIPIENT:
                return "Shipment has been delivered";
            default:
                return "Status unknown";
        }
    }
    
    private PackageStatus getNextStatus(PackageStatus currentStatus) {
        switch (currentStatus) {
            case ORDER_PLACED:
                return PackageStatus.PICKED_UP_BY_COURIER;
            case PICKED_UP_BY_COURIER:
                return PackageStatus.AT_ORIGIN_WAREHOUSE;
            case AT_ORIGIN_WAREHOUSE:
                return PackageStatus.IN_TRANSIT_TO_DESTINATION;
            case IN_TRANSIT_TO_DESTINATION:
                return PackageStatus.AT_DESTINATION_WAREHOUSE;
            case AT_DESTINATION_WAREHOUSE:
                return PackageStatus.OUT_FOR_DELIVERY;
            case OUT_FOR_DELIVERY:
                return PackageStatus.DELIVERED_TO_RECIPIENT;
            default:
                return null; // No next status
        }
    }
    
    private EmailContent getStatusEmailContent(PackageStatus status, int shipmentId) {
    String subject;
    String body;

    switch (status) {
        case ORDER_PLACED:
            subject = "Your shipment has been placed!";
            body = "Hi " + ",\n\n" +
                   "Your shipment request (ID: " + shipmentId + ") has been successfully placed. " +
                   "We will notify you as it progresses through the delivery process.\n\n" +
                   "Thank you for choosing us!";
            break;

        case PICKED_UP_BY_COURIER:
            subject = "Your package has been picked up!";
            body = "Hi " + ",\n\n" +
                   "Your shipment (ID: " + shipmentId + ") has been picked up by the courier and is on its way to the warehouse.\n\n" +
                   "Stay tuned for more updates!";
            break;

        case AT_ORIGIN_WAREHOUSE:
            subject = "Package arrived at origin warehouse";
            body = "Hi " + ",\n\n" +
                   "Your shipment (ID: " + shipmentId + ") has reached the origin warehouse and is being prepared for transit.\n\n" +
                   "We will notify you when it's on the move.";
            break;

        case IN_TRANSIT_TO_DESTINATION:
            subject = "Your package is in transit!";
            body = "Hi " + ",\n\n" +
                   "Your shipment (ID: " + shipmentId + ") is now in transit to the destination warehouse.\n\n" +
                   "We’ll let you know once it arrives.";
            break;

        case AT_DESTINATION_WAREHOUSE:
            subject = "Your package reached the destination warehouse";
            body = "Hi " + ",\n\n" +
                   "Good news! Your shipment (ID: " + shipmentId + ") has arrived at the destination warehouse.\n\n" +
                   "It will be out for delivery soon.";
            break;

        case OUT_FOR_DELIVERY:
            subject = "Your package is out for delivery!";
            body = "Hi " + ",\n\n" +
                   "Your shipment (ID: " + shipmentId + ") is currently out for delivery. " +
                   "Please make sure someone is available to receive it.\n\n" +
                   "Thank you!";
            break;

        case DELIVERED_TO_RECIPIENT:
            subject = "Your package has been delivered!";
            body = "Hi " + ",\n\n" +
                   "We’re happy to let you know that your shipment (ID: " + shipmentId + ") has been successfully delivered.\n\n" +
                   "Thank you for shipping with us!";
            break;

        default:
            subject = "Shipment Status Update";
            body = "Hi " + ",\n\n" +
                   "There has been a status update on your shipment (ID: " + shipmentId + "). Please check your shipment tracking for details.";
            break;
    }

    return new EmailContent(subject, body);
}





